/** Every command id that appears in the menus, for the "disabled" audit and the docs. */
export function menuCommandIds(): string[] {
  const out: string[] = [];
  const walk = (items: MenuEntry[]): void => {
    for (const e of items) {
      if ('sep' in e) continue;
      if ('items' in e) walk(e.items);
      else out.push(e.id);
    }
  };
  for (const m of MENUS) walk(m.items);
  return out;
}
