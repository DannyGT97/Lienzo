// Menu structure of the interface: command ids, our own Spanish labels and the default shortcuts. Whether a command works is decided at runtime by the
// command registry (src/ui/commands.ts): anything without a handler is shown disabled.

/**
 * `short` is the label the narrow (mobile) menu shows when the full one carries an explanation in parentheses: those
 * rows have no room for it there. The desktop menus keep `label`.
 */
export type MenuEntry =
  | { sep: true }
  | { id: string; label: string; short?: string; shortcut?: string; check?: boolean }
  | { label: string; short?: string; items: MenuEntry[]; dynamic?: string };

/** Sub-menus whose rows are made each time they open (the recent files): the page registers what makes them, by the entry's `dynamic` name. */
export const dynamicMenus = new Map<string, () => MenuEntry[]>();

export interface MenuDef {
  id: string;
  label: string;
  items: MenuEntry[];
}

const SEP: MenuEntry = { sep: true };
const i = (id: string, label: string, shortcut?: string, short?: string): MenuEntry => ({ id, label, shortcut, short });
const chk = (id: string, label: string, shortcut?: string): MenuEntry => ({ id, label, shortcut, check: true });
const sub = (label: string, items: MenuEntry[], short?: string): MenuEntry => ({ label, items, short });

